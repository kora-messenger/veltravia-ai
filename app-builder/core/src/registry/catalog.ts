/**
 * The built-in technology catalog (Step 30).
 *
 * This is a PLANNED COMPATIBILITY MATRIX, not a claim of working runtimes:
 *
 * - `scaffold` entries have deterministic starter-file templates in this
 *   package. Nothing about them is built or executed yet.
 * - `planned` entries are documented so specifications and detection can name
 *   them honestly; no template, no build, no test.
 * - No entry in this release is `executable`. The sandbox engine is simulated,
 *   so claiming a real build would be a lie.
 *
 * Commands are argv arrays. A shell string is never stored, so nothing here can
 * turn into command injection later.
 */

import type {
  CommandPlan,
  DeploymentCompatibility,
  FrameworkEntry,
  LanguageEntry,
  PackageManagerDescriptor,
  PreviewCapability,
  RuntimeRequirement,
} from '../types/index.js';

function pm(id: string, installCommand: string, manifestFile: string): PackageManagerDescriptor {
  return { id, installCommand, manifestFile };
}

function cmd(argv: readonly string[], description: string, maxSeconds = 300): CommandPlan {
  return { argv, description, maxSeconds };
}

function preview(
  mode: PreviewCapability['mode'],
  ports: readonly number[],
  note: string,
): PreviewCapability {
  return { mode, ports, note };
}

function deploy(targets: readonly string[], note: string): DeploymentCompatibility {
  return { targets, note };
}

function runtime(
  runtimes: readonly string[],
  compiled: boolean,
  minimumVersion?: string,
): RuntimeRequirement {
  return minimumVersion === undefined
    ? { runtimes, compiled }
    : { runtimes, compiled, minimumVersion };
}

