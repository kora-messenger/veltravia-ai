/** The built-in template set, honestly limited to what is implemented. */
export function createDefaultTemplateRegistry(): TemplateRegistry {
  const registry = new TemplateRegistry();
  registry.register(WEB_REACT_TEMPLATE);
  registry.register(FULLSTACK_REACT_FASTIFY_TEMPLATE);
  return registry;
}
